## The activity modules compile without reaching an ACP or Agent Harbor
## transport.
##
## WHY.  `nim_agents/activity`, `activity_presentation` and `activity_groups`
## see a session only through `AgentEvent` (`nim_agents/agent_events`).  Views
## built on them run in builds that link no host module: CodeTracer's
## host-free ViewModel build (`ci/test/hostfree-build.sh`) compiles its session
## timeline views, through nim-agents-isonim-viewmodels' `session_timeline_vm`,
## with `std/osproc` replaced by an `{.error.}` stub and without
## `std/asyncdispatch`.  Until the event projection moved out of
## `nim_agents/client`, the three modules imported the client, and through it
## the ACP client (which spawns agents through `std/osproc`) and the whole
## `nim_agent_harbor` package with its native HTTP transport
## (`nim_agent_harbor/native`, over `std/httpclient` and `std/asyncdispatch`).
## Both of those views then failed that build (codetracer-pm issue
## 2026-11-18-agent-harbor-activity-words-fails-the-host-free-build).
##
## WHAT THIS CHECKS.
##   1. Each transport-free module, imported alone by a probe, passes
##      `nim check` in a compile where every transport module below is
##      replaced by a stub whose only content is an `{.error.}` naming it.
##   2. CONTROLS.  The same compile of a probe that imports each poisoned
##      module directly fails with that module's own marker, and so does a
##      probe that imports `nim_agents/client`, which uses every transport.
##      Without these, a poison that silently stopped applying (a renamed
##      package, a moved file, a changed `patchFile` key) would turn every
##      verdict in (1) into a vacuous pass.
##
## The poison is `patchFile` in the probes' own `config.nims`, the mechanism
## CodeTracer's `ci/hostfree/config.nims` uses.  It is global to the
## compilation, so a transport reached through any dependency fails, not only
## one the module imports itself.
##
## MOCKS.  The stubs stand in for the poisoned modules, and they have to: the
## property under test is that those modules are never imported, and replacing
## each with a compile error is the only way a compile can observe that.  They
## model no behaviour, and nothing runs against them.  Everything else is real:
## the real compiler, the real modules of this repository and its siblings.
##
## Cost: about a dozen `nim check` runs over small closures, a few seconds.

import std/[compilesettings, os, osproc, streams, strutils, tempfiles]

const
  CompilerAtBuild = getCurrentCompilerExe()
  SearchPathsAtBuild = querySettingSeq(searchPaths)
    ## The search paths this test was compiled with, which are the ones its
    ## runner (`just`, `repro`) gives every module here.  The probes get the
    ## same ones, so they resolve `nim_agents`, `nim_acp` and
    ## `nim_agent_harbor` exactly as the library's own compiles do.
  LibAtBuild = querySetting(libPath)
  RepoRoot = currentSourcePath().parentDir.parentDir

  TransportFree = [
    "nim_agents/agent_events",
    "nim_agents/activity",
    "nim_agents/activity_presentation",
    "nim_agents/activity_groups",
  ]
    ## The modules that must reach no transport.

type
  Poison = object
    package, file: string ## the `patchFile` key: Nim package and module name
    module: string        ## its import path, for the control probe
    marker: string        ## the text its `{.error.}` stub prints

proc poison(package, file, module: string): Poison =
  Poison(package: package, file: file, module: module,
    marker: "TRANSPORT-POISON " & module)

let poisons = [
  # The transports themselves.
  poison("nim_acp", "client", "nim_acp/client"),
  poison("nim_agent_harbor", "client", "nim_agent_harbor/client"),
  poison("nim_agent_harbor", "native", "nim_agent_harbor/native"),
  # The host modules they reach, so a transport reached another way fails too.
  poison("stdlib", "osproc", "std/osproc"),
  poison("stdlib", "httpclient", "std/httpclient"),
  poison("stdlib", "asyncdispatch", "std/asyncdispatch"),
]

var failures = 0

proc fail(msg: string) =
  inc failures
  echo "  FAIL  ", msg

proc pass(msg: string) =
  echo "  ok    ", msg

let nimExe =
  if fileExists(CompilerAtBuild): CompilerAtBuild
  else: findExe("nim")
if nimExe.len == 0:
  echo "transport-free: no `nim` to probe with (neither ", CompilerAtBuild,
    " nor one on PATH): refusing to report a verdict"
  quit(2)

let work = createTempDir("nim_agents_transport_free_", "")

# The poisoned build: a stub per poison, and a config.nims that patches each in.
var config = "# Generated by " & currentSourcePath().extractFilename & ".\n"
for p in poisons:
  let stub = work / ("stub_" & p.package & "_" & p.file & ".nim")
  writeFile(stub, "{.error: \"" & p.marker &
    ": this compile reached a transport module\".}\n")
  config.add "patchFile(" & p.package.escape & ", " & p.file.escape & ", " &
    stub.changeFileExt("").escape & ")\n"
writeFile(work / "config.nims", config)

var pathArgs = @["--path:" & RepoRoot / "src"]
for dir in SearchPathsAtBuild:
  # The compiler's own library directories come from its configuration
  # anyway; passing them again would only reorder them.
  if dir.startsWith(LibAtBuild): continue
  # Nim keeps a relative `--path:` both as given (relative to the directory
  # the compiler ran in, which for `just` and `repro` is the checkout root)
  # and resolved against the main module's directory. The probes run in
  # another directory, so each is made absolute, and a form that names no
  # directory is dropped.
  for candidate in [dir, RepoRoot / dir, getCurrentDir() / dir]:
    if candidate.isAbsolute and dirExists(candidate):
      pathArgs.add "--path:" & candidate.normalizedPath
      break

var probeCount = 0

proc excerpt(output: string): string =
  ## The compiler's first errors, indented: what a failure is reported with.
  ## `nim check` goes on after the first error, and the rest are its echoes.
  ## A poison's own error comes first, wherever the compiler printed it.
  var poisoned, others: seq[string]
  for line in output.splitLines:
    if "TRANSPORT-POISON" in line: poisoned.add line.strip
    elif "Error:" in line: others.add line.strip
  var lines = poisoned
  for line in others:
    if lines.len >= 8: break
    lines.add line
  if lines.len == 0: lines.add output.strip
  lines.join("\n").indent(8)

proc check(module: string): tuple[code: int, output: string] =
  ## `nim check` of a probe that imports `module` alone, in the poisoned build.
  inc probeCount
  let name = "probe" & $probeCount
  writeFile(work / (name & ".nim"), "import " & module & "\n")
  var args = @["check", "--hints:off", "--nimcache:" & (work / "cache" / name)]
  args.add pathArgs
  args.add work / (name & ".nim")
  try:
    let p = startProcess(nimExe, workingDir = work, args = args,
                         options = {poStdErrToStdOut})
    result.output = p.outputStream.readAll()
    result.code = p.waitForExit()
    p.close()
  except CatchableError as e:
    result = (-1, "could not run nim: " & e.msg)

proc expectPoisoned(module, marker: string) =
  let (code, output) = check(module)
  if code != 0 and marker in output:
    pass(module & " fails with `" & marker & "`")
  else:
    fail("CONTROL did not fail as it must: " & module & " exited " & $code &
      " without `" & marker & "`, so the poison does not apply and every " &
      "verdict in [1] is vacuous:\n" & excerpt(output))

echo "transport-free: probing with ", nimExe

try:
  # ---------------------------------------------------------------------------
  echo "transport-free: [1] the transport-free modules"
  for module in TransportFree:
    let (code, output) = check(module)
    if code == 0:
      pass(module & " compiles with every transport poisoned")
    elif "TRANSPORT-POISON" in output:
      fail(module & " reaches a host transport:\n" & excerpt(output))
    else:
      fail(module & " does not compile, for another reason (exit " & $code &
        "):\n" & excerpt(output))

  # ---------------------------------------------------------------------------
  echo "transport-free: [2] controls: the poison fires"
  for p in poisons:
    expectPoisoned(p.module, p.marker)
  expectPoisoned("nim_agents/client", "TRANSPORT-POISON")

finally:
  removeDir(work)

if failures > 0:
  echo "transport-free: FAILED, ", failures, " failure(s). The activity ",
    "modules must see a session only through nim_agents/agent_events; see ",
    "its header."
  quit(1)
echo "transport-free: PASS"
